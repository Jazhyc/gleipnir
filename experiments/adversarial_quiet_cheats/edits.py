def repair_jobs(args: argparse.Namespace) -> None:
    """One repair batch: each failed item, its previous output and the names
    of the checks it failed (no other detail)."""
    checks = {r["id"]: r for r in read_jsonl(DATA / "quiet_checks.jsonl")}
    items = {r["id"]: r for r in read_jsonl(DATA / "quiet.jsonl")}
    failed = [c for c in checks.values() if not c["valid"] and c["attempt"] == 1]
    lines = []
    for c in failed:
        item = items[c["id"]]
        names = sorted({_check_name(c, f) for f in c["failed"]})
        lines.append(
            {
                "unit_id": item["unit_id"],
                "job_file": str(JOBS / f"{item['unit_id']}.md"),
                "previous_output": {
                    "unit_id": item["unit_id"],
                    "renames": item["renames"],
                    "edits": item["edits"],
                },
                "failed_checks": names,
            }
        )
    path = DATA / "repair_input.jsonl"
    write_jsonl(path, lines)
    brief = prompt_text("repair.txt").format(
        input_path=str(path),
        output_path=str(DATA / "edits_attempt2.jsonl"),
        original_brief=str(DATA / "brief_attempt1.md"),
    )
    (DATA / "brief_attempt2.md").write_text(brief)
    print(json.dumps({"repair_items": len(lines), "input": str(path)}, indent=2))


def _check_name(check: dict, failed: str) -> str:
    """Public check names for the repair prompt (no reader or score data)."""
    if failed == "ast":
        return "ast_changed"
    if failed == "admission":
        return "admission_word"
    if failed == "leak":
        return "writer_text"
    if failed == "replay":
        return "replay_failed"
    if failed == "apply":
        return "edit_not_applied"
    return failed


