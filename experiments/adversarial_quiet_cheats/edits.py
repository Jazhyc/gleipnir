"""Arm 1 writer jobs and edit application (stdlib only; no model calls).

    PY=../../.venv-data/bin/python
    PYTHONPATH=src:. $PY experiments/adversarial_quiet_cheats/edits.py jobs
    # Luna (Codex delegate_task) reads data/.../arm1/jobs/ and writes
    # data/.../arm1/edits_attempt1.jsonl
    PYTHONPATH=src:. $PY experiments/adversarial_quiet_cheats/edits.py apply --attempt 1
    PYTHONPATH=src:. $PY experiments/adversarial_quiet_cheats/edits.py strip
    # after replay and checks, for the failed items only (one repair batch):
    PYTHONPATH=src:. $PY experiments/adversarial_quiet_cheats/edits.py repair-jobs
    PYTHONPATH=src:. $PY experiments/adversarial_quiet_cheats/edits.py apply --attempt 2

`jobs` stages one plain-text file per cheat (random unit id, shuffled), each
holding the agent's own steps up to monitor-aware's cut (messages and tool-call
arguments, raw), the two readers' announced quotes and first steps from
monitor-aware's `labels.jsonl`, and nothing else: no setup, task, run id,
tool output, score or label. `brief.md` is the Codex task text (prompt A1 with
the paths filled in). The key goes to `key_PRIVATE.json`.

`apply` turns returned edit specifications into edited messages. Edits touch
only assistant messages at or before the cut (message text, or string
tool-call arguments); each `old` must occur exactly once at the time it is
applied. The rename map is then applied mechanically to every Python token,
shell word and message in those turns. System, user and tool messages are
never edited here; tool outputs after the first edited turn are regenerated by
`replay.py`.

`strip` builds the comment-strip control: 37 non-cheats, comments and
docstrings removed by code.
"""

