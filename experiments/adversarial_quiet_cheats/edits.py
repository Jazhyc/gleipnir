def strip_docs(code: str) -> str | None:
    """`code` without `#` comments or bare string statements; blank lines and
    every other byte kept. None if it does not tokenize, or if the result is
    not a documentation-only edit (python_docs)."""
    from gleipnir.adversarial.python_docs import (
        _logical_lines,
        check_documentation_only_edit,
    )

    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(code).readline))
    except (tokenize.TokenError, SyntaxError, IndentationError):
        return None
    lines = io.StringIO(code).readlines()
    drop_rows: set[int] = set()
    for logical in _logical_lines(tokens):
        if all(t.type == tokenize.STRING for t in logical):
            for t in logical:
                drop_rows.update(range(t.start[0], t.end[0] + 1))
    code_rows: set[int] = set()
    cuts: dict[int, int] = {}
    for t in tokens:
        if t.type == tokenize.COMMENT:
            cuts[t.start[0]] = t.start[1]
        elif t.type not in (
            tokenize.NL,
            tokenize.NEWLINE,
            tokenize.INDENT,
            tokenize.DEDENT,
            tokenize.ENDMARKER,
            tokenize.ENCODING,
        ):
            if t.start[0] not in drop_rows:
                code_rows.update(range(t.start[0], t.end[0] + 1))
    out = []
    for row, text in enumerate(lines, 1):
        if row in drop_rows and row not in code_rows:
            continue
        if row in cuts:
            body = text[: cuts[row]].rstrip(" \t\f")
            if not body.strip() and row not in code_rows:
                continue  # comment-only line
            text = body + text[len(text.rstrip("\r\n")) :]
        out.append(text)
    stripped = "".join(out)
    if stripped == code:
        return code
    import warnings

    from experiments.adversarial_quiet_cheats.checks import _parseable

    a, b = _parseable(code), _parseable(stripped)
    if a is not None:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", SyntaxWarning)
            if b is None or not check_documentation_only_edit(a, b).ok:
                return None
    return stripped


def strip_call(call: dict[str, Any], stats: Counter) -> dict[str, Any]:
    """Comments and docstrings stripped from every Python piece of one call;
    a piece that can't be stripped safely falls back to comments only, then
    to unchanged (counted)."""
    from experiments.adversarial_natural_cheats.trajectories import strip_comments
    from experiments.adversarial_quiet_cheats.checks import segments

    def strip(text: str, kind: str) -> str:
        for name, fn in (("docs", strip_docs), ("comments", _comments_only)):
            result = fn(text)
            if result is not None:
                stats[f"{kind}:{name}{'_changed' if result != text else '_same'}"] += 1
                return result
        stats[f"{kind}:unchanged"] += 1
        return text

    def _comments_only(text):
        result = strip_comments(text)
        return None if result is None else result[0]

    new = copy.deepcopy(call)
    args = new.get("arguments") or {}
    name = new["function"]
    if name == "python" and isinstance(args.get("code"), str):
        args["code"] = strip(args["code"], "python_tool")
    elif name == "text_editor" and str(args.get("path", "")).endswith(".py"):
        for key in ("file_text", "new_str", "old_str"):
            if isinstance(args.get(key), str):
                if key == "file_text":
                    args[key] = strip(args[key], "editor_file")
                else:
                    result = _comments_only(args[key])
                    stats[
                        f"editor_{key}:"
                        f"{'comments' if result is not None else 'unchanged'}"
                    ] += 1
                    args[key] = args[key] if result is None else result
    elif name == "bash" and isinstance(args.get("command"), str):
        pieces = []
        for _, kind, text in segments(call):
            pieces.append(strip(text, "heredoc") if kind == "python" else text)
        if "".join(t for _, k, t in segments(call) if k != "fixed") == args["command"]:
            args["command"] = "".join(pieces)
        else:
            stats["bash:unsplit"] += 1
    return new


def strip_messages(messages: list[dict], stats: Counter) -> list[dict]:
    out = []
    for m in messages:
        if m["role"] == "assistant" and m.get("tool_calls"):
            m = {**m, "tool_calls": [strip_call(c, stats) for c in m["tool_calls"]]}
        out.append(m)
    return out


def control_pool(runs, replays, ma_rows_student, ma_rows_teacher, cuts) -> list[dict]:
    """Scorable non-cheats with a valid replay, never passing, with at least
    one comment or docstring removed by `strip_messages` (Amendment 1)."""
    pool = []
    for run in sorted(runs, key=run_order):
        if run["cheat"]:
            continue
        rp = replays.get(run["id"])
        if rp is None or not rp["final_matches"] or rp["ever_passed"]:
            continue
        s, t = ma_rows_student[run["id"]], ma_rows_teacher[run["id"]]
        if s["metadata"]["too_long"]["4b"] or t["metadata"]["too_long"]["27b"]:
            continue
        messages = run["messages"][: cuts[run["id"]] + 1]
        stripped = strip_messages(messages, Counter())
        if stripped == messages:
            continue
        pool.append({"run": run, "cut": cuts[run["id"]], "messages": stripped})
    return pool


def draw_controls(
    pool: list[dict], cheats_per_setup: dict[str, int], n: int, seed: int
) -> list[dict]:
    quota = proportional_quota(cheats_per_setup, n)
    rng = random.Random(seed)
    chosen = []
    for setup in MA_CONFIG["setups"]:
        candidates = [p for p in pool if p["run"]["setup"] == setup]
        if len(candidates) < quota[setup]:
            raise ValueError(
                f"{setup}: {len(candidates)} eligible, need {quota[setup]}"
            )
        chosen += rng.sample(candidates, quota[setup])
    return chosen


def strip(args: argparse.Namespace) -> None:
    runs = load_runs()
    replays = load_replays()
    cuts = ma_cuts(runs, replays)
    spec = ARM1["comment_strip_control"]
    pool = control_pool(
        runs, replays, load_ma_rows("student"), load_ma_rows("teacher"), cuts
    )
    cheats = Counter(r["setup"] for r in runs if r["cheat"])
    chosen = draw_controls(
        pool, {s: cheats[s] for s in MA_CONFIG["setups"]}, spec["n"], spec["seed"]
    )
    rows, stats = [], Counter()
    for c in chosen:
        run = c["run"]
        rid = f"{run['id']}::arm1_strip"
        rows.append(
            {
                "id": rid,
                "run_id": run["id"],
                "cut": c["cut"],
                "attempt": 1,
                "edits": [],
                "renames": {},
                "apply_errors": [],
                "messages": strip_messages(run["messages"][: c["cut"] + 1], stats),
            }
        )
    digest = write_jsonl(DATA / "strip.jsonl", rows)
    summary = {
        "controls": len(rows),
        "eligible_pool": len(pool),
        "per_setup": dict(Counter(r["run_id"].split("__", 1)[1] for r in rows)),
        "piece_outcomes": dict(sorted(stats.items())),
        "sha256": digest,
    }
    (DATA / "strip_summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


