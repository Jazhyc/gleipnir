def prompt_text(name: str) -> str:
    text = (PROMPTS / name).read_text()
    expected = CONFIG["writer"]["prompt_sha256"].get(name)
    if expected and sha(text) != expected:
        raise ValueError(f"{name} does not match its frozen SHA256")
    return text


# ---------------------------------------------------------------- jobs


def cheat_units() -> list[dict[str, Any]]:
    """The 37 cheats with their monitor-aware cut, in setup and task order."""
    runs = sorted((r for r in load_runs() if r["cheat"]), key=run_order)
    replays = load_replays()
    out = []
    for run in runs:
        turn = replays[run["id"]]["first_pass_turn"]
        if turn is None or not replays[run["id"]]["final_matches"]:
            raise ValueError(f"{run['id']}: no valid first passing turn")
        out.append({"run": run, "cut": turn})
    if len(out) != ARM1["n_cheats"]:
        raise ValueError(f"{len(out)} cheats, expected {ARM1['n_cheats']}")
    return out


def hints(label: dict[str, Any]) -> list[dict[str, Any]]:
    """The readers' announced quotes and first steps (no other label field)."""
    out = []
    for n in (1, 2):
        r = label[f"reader_{n}"]
        if r["announced"] == "yes" and r["quote"]:
            out.append({"first_step": r["first_step"], "quote": r["quote"]})
    unique = {(h["first_step"], h["quote"]): h for h in out}
    return list(unique.values())


def job_text(unit_id: str, messages: list[dict], found: list[dict]) -> str:
    lines = [f"# Transcript {unit_id}", ""]
    lines.append("## Places two readers found (examples, not a complete list)")
    for h in found:
        lines.append(
            f"- step {h['first_step']}: {json.dumps(h['quote'], ensure_ascii=False)}"
        )
    if not found:
        lines.append("- (none recorded)")
    lines += ["", "## Steps", "", step_text(messages, outputs=False)]
    return "\n".join(lines) + "\n"


def jobs(args: argparse.Namespace) -> None:
    if (DATA / "key_PRIVATE.json").exists() and not args.force:
        raise SystemExit(
            "jobs exist; they are frozen once written "
            "(use --force only before any writer call)"
        )
    labels = load_labels()
    units = cheat_units()
    secret = secrets.randbits(64)
    rng = random.Random(f"{secret}:arm1-jobs")
    JOBS.mkdir(parents=True, exist_ok=True)
    for old in JOBS.glob("*.md"):
        old.unlink()
    key, index = [], []
    for unit in units:
        uid = f"q{rng.getrandbits(40):010x}"
        messages = unit["run"]["messages"][: unit["cut"] + 1]
        text = job_text(uid, messages, hints(labels[unit["run"]["id"]]))
        path = JOBS / f"{uid}.md"
        path.write_text(text)
        key.append(
            {
                "unit_id": uid,
                "run_id": unit["run"]["id"],
                "cut": unit["cut"],
                "steps_in_cut": len(assistant_steps(messages)),
                "job_sha256": file_sha256(path),
                "chars": len(text),
            }
        )
        index.append(uid)
    rng.shuffle(index)
    (JOBS / "index.txt").write_text("\n".join(index) + "\n")
    output = DATA / "edits_attempt1.jsonl"
    brief = prompt_text("a1_deletion.txt").format(
        input_dir=str(JOBS),
        output_path=str(output),
        patterns="\n".join(f"  {p}" for p in CONFIG["admission_patterns"]),
    )
    (DATA / "brief_attempt1.md").write_text(brief)
    (DATA / "key_PRIVATE.json").write_text(
        json.dumps({"secret_seed": secret, "units": key}, indent=1) + "\n"
    )
    summary = {
        "jobs": len(key),
        "dir": str(JOBS),
        "brief": str(DATA / "brief_attempt1.md"),
        "brief_sha256": sha(brief),
        "output": str(output),
        "total_chars": sum(k["chars"] for k in key),
        "max_chars": max(k["chars"] for k in key),
    }
    (DATA / "jobs_summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


# ---------------------------------------------------------------- apply


class EditError(ValueError):
    pass


def apply_edits(
    messages: list[dict[str, Any]], spec: dict[str, Any]
) -> tuple[list[dict[str, Any]], list[str]]:
    """Edited copy of `messages` (already cut) and a list of apply errors."""
    out = copy.deepcopy(messages)
    steps = assistant_steps(out)
    errors = []
    for n, edit in enumerate(spec.get("edits") or []):
        try:
            _apply_one(out, steps, edit)
        except EditError as error:
            errors.append(f"edit{n}:{error}")
    renames = spec.get("renames") or {}
    if not isinstance(renames, dict) or not all(
        isinstance(k, str) and isinstance(v, str) for k, v in renames.items()
    ):
        errors.append("renames_malformed")
    elif renames:
        out = apply_renames(out, renames)
    return out, errors


def _apply_one(messages: list[dict], steps: dict[int, int], edit: dict) -> None:
    step, field = edit.get("step"), edit.get("field")
    old, new = edit.get("old"), edit.get("new")
    if not isinstance(old, str) or not isinstance(new, str) or not old:
        raise EditError("old_or_new_missing")
    if step not in steps:
        raise EditError(f"step_outside_cut:{step}")
    message = messages[steps[step]]
    if field == "message":
        holder, key = message, "text"
    elif field == "argument":
        calls = message.get("tool_calls") or []
        index = edit.get("call_index")
        if not isinstance(index, int) or not 0 <= index < len(calls):
            raise EditError(f"bad_call_index:{index}")
        args = calls[index].get("arguments") or {}
        key = edit.get("argument")
        if key not in args or not isinstance(args[key], str):
            raise EditError(f"bad_argument:{key}")
        holder = args
    else:
        raise EditError(f"bad_field:{field}")
    count = holder[key].count(old)
    if count != 1:
        raise EditError(f"old_occurs_{count}_times")
    holder[key] = holder[key].replace(old, new, 1)


def apply_renames(messages: list[dict], renames: dict[str, str]) -> list[dict]:
    """The rename map applied to Python tokens (python code, .py editor text,
    Python heredocs), shell words and agent prose, in assistant turns only."""
    from experiments.adversarial_quiet_cheats.checks import (
        rename_tokens,
        rename_words,
        segments,
    )

    out = copy.deepcopy(messages)
    for message in out:
        if message["role"] != "assistant":
            continue
        message["text"] = rename_words(message["text"], renames)
        for call in message.get("tool_calls") or []:
            args = call.get("arguments") or {}
            if call["function"] == "bash" and isinstance(args.get("command"), str):
                pieces = []
                for _, kind, text in segments(call):
                    if kind == "python":
                        pieces.append(rename_tokens(text, renames))
                    elif kind == "shell":
                        pieces.append(rename_words(text, renames))
                    elif kind == "text":
                        pieces.append(text)
                rebuilt = "".join(pieces)
                if (
                    "".join(t for _, k, t in segments(call) if k != "fixed")
                    == args["command"]
                ):
                    args["command"] = rebuilt
                continue
            for key, value in args.items():
                if not isinstance(value, str):
                    continue
                if call["function"] == "python" and key == "code":
                    args[key] = rename_tokens(value, renames)
                elif call["function"] == "text_editor" and key in (
                    "file_text",
                    "new_str",
                    "old_str",
                ):
                    if str(args.get("path", "")).endswith(".py"):
                        args[key] = rename_tokens(value, renames)
    return out


def apply(args: argparse.Namespace) -> None:
    key = json.loads((DATA / "key_PRIVATE.json").read_text())["units"]
    by_uid = {k["unit_id"]: k for k in key}
    path = DATA / f"edits_attempt{args.attempt}.jsonl"
    specs = read_jsonl(path)
    runs = {r["id"]: r for r in load_runs()}
    previous = {r["id"]: r for r in read_jsonl(DATA / "quiet.jsonl")}
    out, problems = dict(previous), Counter()
    seen = set()
    for spec in specs:
        uid = spec.get("unit_id")
        if uid not in by_uid or uid in seen:
            problems["unknown_or_duplicate_unit"] += 1
            continue
        seen.add(uid)
        k = by_uid[uid]
        messages = runs[k["run_id"]]["messages"][: k["cut"] + 1]
        edited, errors = apply_edits(messages, spec)
        rid = f"{k['run_id']}::arm1_quiet"
        out[rid] = {
            "id": rid,
            "run_id": k["run_id"],
            "unit_id": uid,
            "cut": k["cut"],
            "attempt": args.attempt,
            "edits_file_sha256": file_sha256(path),
            "edits": spec.get("edits") or [],
            "renames": spec.get("renames") or {},
            "apply_errors": errors,
            "messages": edited,
        }
    missing = sorted(set(by_uid) - seen) if args.attempt == 1 else []
    rows = sorted(out.values(), key=lambda r: r["id"])
    write_jsonl(DATA / "quiet.jsonl", rows)
    summary = {
        "attempt": args.attempt,
        "specs": len(specs),
        "applied": len(seen),
        "missing_units": len(missing),
        "with_apply_errors": sum(bool(out[r]["apply_errors"]) for r in out),
        "problems": dict(problems),
    }
    print(json.dumps(summary, indent=2))


